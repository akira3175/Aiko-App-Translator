import assert from 'node:assert/strict';
import {fixture} from './helpers/polish_review_fixture.mjs';
import {reviewedText} from '../web/features/polish-review.js';
const {$,feature,cm,state,review,server,calls,reloads,normalSaves,window,open,click,close}=fixture();
const tick=()=>new Promise(resolve=>setImmediate(resolve));
open();assert.equal(state.polishReview,true);assert.equal($('#saveButton').textContent,'Lưu bản đang duyệt');
$('.polish-inline-old').click();assert.equal(cm.getValue(),review.proposed,'Clicking old text must not restore it');
cm.replaceRange('Tự sửa ',{line:0,ch:2});
await feature.flush();assert.equal(calls.at(-1).action,'draft');assert.equal(feature.active,true);
const saved=cm.getValue();
server.latest={...structuredClone(review),revision:1,draft_text:saved};
feature.open(server.latest);assert.equal(cm.getValue(),saved,'Reload must restore the full draft');
cm.replaceRange('Mới ',{line:2,ch:0});await feature.accept();
assert.deepEqual(calls.slice(-2).map(item=>item.action),['draft','accept']);assert.equal(calls.at(-1).revision,2);
assert.equal(feature.active,false);assert.deepEqual(reloads.at(-1),['v1_c1_s1.md','Demo']);
open();cm.replaceRange('Lưu lỗi ',{line:2,ch:0});server.fail=true;
assert.equal(await feature.flush(),false);const before=calls.length;await feature.accept();
assert.equal(calls.length,before+1);assert.equal(feature.active,true);assert.equal($('[data-review-recovery]').hidden,false);
server.fail=false;window.confirm=()=>true;
click('reload');await tick();assert.equal(cm.getValue(),saved);
let confirmation='';window.confirm=text=>{confirmation=text;return false;};
click('discard');await tick();assert.match(confirmation,/các chỉnh sửa/);assert.equal(feature.active,true);
window.confirm=()=>true;server.reloadFails=true;click('discard');await tick();assert.equal(calls.at(-1).action,'discard');assert.equal(feature.active,false);
assert.equal(cm.getValue(),server.liveText,'Discard must restore authoritative text even if the follow-up chapter GET fails');
assert.equal(state.dirty,false);
assert.deepEqual(normalSaves,[],'Review draft saves must never go through ordinary chapter saving');
$('#autosave').checked=true;
cm.replaceRange(' thêm',{line:0,ch:cm.getLine(0).length});
await new Promise(resolve=>setTimeout(resolve,1250));
assert.deepEqual(normalSaves,[server.liveText+' thêm'],'Editing after a failed reload must save from the authoritative original, not the discarded proposal');
server.reloadFails=false;
open();cm.replaceRange('Lần một ',{line:2,ch:0});
let release;server.hold=new Promise(resolve=>{release=resolve;});
const saving=feature.flush();cm.replaceRange('Lần hai ',{line:2,ch:0});release();server.hold=null;
assert.equal(await saving,true);assert.equal(calls.at(-1).draft_text,cm.getValue());
const malicious={...structuredClone(review),original:'<img src=x onerror=alert(1)>\n'};
feature.open(malicious);assert.equal($('.polish-inline-old img'),null);
server.latest=null;server.reloadFails=true;
click('reload');await tick();assert.equal(feature.active,false);
assert.equal(cm.getValue(),server.liveText,'Recovery after another tab discards must restore authoritative text before enabling ordinary editing');
assert.equal(reviewedText(review,review.values),review.proposed);
close();console.log('inline review lifecycle checks passed: draft/reload, accept/discard, failure/recovery, concurrent typing, legacy migration, escaping');
