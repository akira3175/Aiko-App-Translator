import assert from 'node:assert/strict';
import {fixture} from './helpers/polish_review_fixture.mjs';
const {$,feature,editorFeature,cm,state,review,calls,open,click,close}=fixture();
const settle=()=>new Promise(resolve=>setTimeout(resolve,150));
const marked=()=>Array.from(cm.getAllMarks()).filter(mark=>mark.className==='polish-diff-added').map(mark=>{const {from,to}=mark.find();return cm.getRange(from,to);});
const initialEditors=document.querySelectorAll('.CodeMirror').length;
open();
assert.equal(editorFeature.views.target,cm,'Review must reuse the existing target editor');
assert.equal(document.querySelectorAll('.CodeMirror').length,initialEditors,'No per-paragraph editors');
assert.ok($('#targetEditorShell').contains($('.polish-inline-hunk')),'Old text must be a line widget inside the editor');
assert.equal(cm.getValue(),review.proposed);
assert.ok(marked().includes('dễ'));assert.equal($('.polish-diff-removed').textContent,'khó');
assert.equal($('[data-change-position]').textContent,'1 / 2');
click('next-change');assert.equal($('[data-change-position]').textContent,'2 / 2');
assert.equal($('[data-review-action="next-change"]').disabled,true);
click('previous-change');assert.equal($('[data-change-position]').textContent,'1 / 2');
cm.replaceRange('rất ',{line:2,ch:8},undefined,'user-edit');await settle();
assert.ok(marked().join('').includes('rất'));
assert.equal(state.dirty,false,'Review edits must not enter ordinary chapter autosave');
await feature.flush();assert.equal(calls.at(-1).draft_text,cm.getValue());
assert.ok(!calls.at(-1).draft_text.includes('<mark'));
const edited=cm.getValue();
click('old');assert.ok(cm.getValue().includes('Câu này khó hiểu.'));assert.equal($('[data-hunk="0"] .polish-inline-old'),null);
click('ai');assert.equal(cm.getValue(),review.proposed);
click('undo');assert.ok(cm.getValue().includes('Câu này khó hiểu.'));
click('undo');assert.equal(cm.getValue(),edited);
// Edit an unchanged area and cross multiple original paragraph boundaries.
cm.replaceRange('Gộp đoạn\nĐoạn tự thêm\n',{line:2,ch:0},{line:5,ch:0},'cross-paragraph');await settle();
assert.ok(cm.getValue().includes('Gộp đoạn\nĐoạn tự thêm\n'));
await feature.flush();assert.equal(calls.at(-1).draft_text,cm.getValue());
cm.undo();await settle();assert.equal(cm.getValue(),edited);
const unfreeze=feature.freeze();const before=cm.getValue();
assert.equal(cm.getOption('readOnly'),true);
cm.replaceRange('MUST NOT WRITE',{line:0,ch:0});assert.equal(cm.getValue(),before,'Freeze must also block programmatic formatting/replace');
unfreeze();assert.equal(cm.getOption('readOnly'),false);
cm.execCommand('selectAll');assert.equal(cm.getSelection(),cm.getValue(),'Select all/copy must exclude red old text');
feature.open(null);
assert.equal(editorFeature.views.target,cm);assert.equal(document.querySelectorAll('.CodeMirror').length,initialEditors);
assert.equal($('.polish-inline-hunk'),null);assert.equal(cm.getAllMarks().filter(mark=>mark.className==='polish-diff-added').length,0);
assert.ok(!cm.getOption('gutters').includes('polish-diff-gutter'));
feature.open({...review,original:'same',proposed:'same',draft_text:'same'});
assert.equal($('[data-change-position]').textContent,'0 / 0');assert.equal($('[data-review-action="next-change"]').disabled,true);
close();
console.log('inline CodeMirror checks passed: original editor reuse, line widgets, native editing/undo, cross-paragraph changes, selection, freeze, cleanup');
